import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import QRCode from 'qrcode';
import jsQR from 'jsqr';
import { PNG } from 'pngjs';

// Exercise the real local store with browser storage and the cloud adapter stubbed.
// This catches demo-mode regressions without talking to the hosted database.
const memory = new Map();
globalThis.localStorage = {getItem:key=>memory.get(key)??null,setItem:(key,value)=>memory.set(key,value),removeItem:key=>memory.delete(key)};
const source = (await readFile(new URL('../src/store.js', import.meta.url),'utf8')).replace(/^import[^\n]+\n/, `const cloudEnabled=false, cloudCache={}, cloudUserId=()=>null, cloudAction=()=>{}, uploadCover=()=>{}, notifyStore=()=>{}, supabase=null;\n`);
const store = await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
const owner={id:'owner',name:'Lender',lat:42.36,lng:-71.06};
const reader={id:'reader',name:'Reader',lat:42.37,lng:-71.05};
store.saveUser(owner);
const group=await store.communityAction('createGroup',{name:'Demo campus'});
const book=await store.addBook({title:'Bundle',author:'Various',condition:'Good',genre:'fiction',lat:owner.lat,lng:owner.lng,ownerId:owner.id,ownerName:owner.name,groupId:group.id,bundleItems:['Book A','Book B'],exchangeMode:'loan',loanDays:7});
store.saveUser(reader);
assert.equal(store.getNearbyBooks(reader.lat,reader.lng).length,0);
await store.communityAction('joinGroup',{groupId:group.id});
assert.equal(store.getNearbyBooks(reader.lat,reader.lng).length,1);
const request=await store.createRequest({bookId:book.id,bookTitle:book.title,ownerId:owner.id,requesterId:reader.id,requesterName:reader.name});
store.saveUser(owner); await store.updateRequestStatus(request.id,'accepted');
store.saveUser(reader); await store.setRequestAvailability(request.id,['sat']);
store.saveUser(owner); await store.confirmSlot(request.id,'sat','Library');
const code=await store.communityAction('mintHandoff',{requestId:request.id});
const link=`https://bookswap-beige.vercel.app/handoff/${request.id}?code=${encodeURIComponent(code.handoffCode)}`;
const data=await QRCode.toDataURL(link,{width:240,margin:4,errorCorrectionLevel:'M'});
const png=PNG.sync.read(Buffer.from(data.split(',')[1],'base64'));
const decoded=jsQR(new Uint8ClampedArray(png.data),png.width,png.height);
assert.equal(decoded.data,link);
store.saveUser(reader);
await assert.rejects(()=>store.communityAction('completeHandoff',{requestId:request.id,code:'bad'}),/Invalid/);
await store.communityAction('completeHandoff',{requestId:request.id,code:code.handoffCode,note:'Thanks'});
assert.equal(store.getBooks()[0].status,'lent');
assert.equal(store.getRequests()[0].status,'loaned');
await assert.rejects(()=>store.communityAction('completeHandoff',{requestId:request.id,code:code.handoffCode}),/Invalid/);
store.saveUser(owner); await store.communityAction('returnLoan',{requestId:request.id});
assert.equal(store.getBooks()[0].status,'available');
store.saveUser(reader);
assert.equal((await store.createRequest({bookId:book.id,bookTitle:book.title,ownerId:owner.id,requesterId:reader.id,requesterName:reader.name})).status,'pending');
await store.communityAction('reportBook',{bookId:book.id,reason:'Misleading listing',details:'Test report'});
assert.equal(store.getReports().length,1);
await store.communityAction('blockUser',{targetId:owner.id,targetName:owner.name});
assert.equal(store.getNearbyBooks(reader.lat,reader.lng).length,0);
await assert.rejects(()=>store.sendMessage({requestId:request.id,text:'Blocked',senderId:reader.id}),/blocked/);
await store.communityAction('unblockUser',{targetId:owner.id});
assert.equal(store.getNearbyBooks(reader.lat,reader.lng).length,1);
console.log('PASS: local group/bundle/loan lifecycle, report/block/unblock, and QR decoding to the exact handoff URL.');
